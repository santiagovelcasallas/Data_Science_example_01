"""Phase 2 — The Generator: de novo solvent design.

Backends
--------
``reinvent``   REINVENT 4 staged-learning (reinforcement learning). The reward is
               computed by :mod:`alumina_pipeline.reinvent_scorer`, which REINVENT
               calls through its ``ExternalProcess`` scoring component. That scorer
               combines (a) the IL/DES class check, (b) the toxicity / volatility
               penalties and (c) the BoTorch acquisition value from Phase 4. The
               agent checkpoint is carried from round to round, so the generator's
               weights are what the optimiser actually updates.
``enumerator`` Combinatorial fallback (no ML, no GPU, no prior file). Used to
               smoke-test the loop.
"""

from __future__ import annotations

import logging
import random
import shlex
import subprocess
import sys
from pathlib import Path

import pandas as pd

from .chem_space import Candidate, assemble, enumerate_generated
from .config import resolve

log = logging.getLogger("alumina.phase2")

# Hard-zero SMARTS handed to REINVENT's custom_alerts component so the agent is
# pushed away from them during RL itself (the scorer also penalises them).
TOXIC_SMARTS = [
    "[N+](=O)[O-]",          # nitro
    "N=N",                   # azo
    "[SH]",                  # thiols
    "C(=O)Cl", "S(=O)(=O)Cl",  # acyl / sulfonyl halides
    "[N;R0]=[C;R0]=[O,S]",   # (thio)isocyanates
    "C1OC1", "C1NC1",        # epoxides, aziridines
    "[CH2]=[CH]C=O",         # Michael acceptors (acrolein-like)
    "[Hg,Pb,Cd,As,Se,Tl]",   # heavy metals
    "OO",                    # peroxides
    "[CX4][Cl,Br,I]",        # alkyl halides
]


class SolventGenerator:
    def __init__(self, cfg: dict, run_dir: Path, scorer_config: Path, seed: int = 0, device: str = "cpu"):
        self.cfg = cfg
        self.run_dir = run_dir
        self.scorer_config = scorer_config
        self.rng = random.Random(seed)
        self.device = device
        self.agent_file: Path | None = None  # REINVENT agent checkpoint, evolves each round

    # ------------------------------------------------------------------
    def propose(self, round_idx: int, exclude: set[str]) -> list[Candidate]:
        if self.cfg["backend"] == "reinvent":
            generated = self._run_reinvent(round_idx)
        else:
            generated = enumerate_generated(self.rng, self.cfg["solvent_classes"])

        pool: list[Candidate] = []
        for g in generated:
            pool += [c for c in assemble(g, self.cfg["solvent_classes"]) if c.smiles not in exclude]
        self.rng.shuffle(pool)
        pool = pool[: self.cfg["pool_size"]]
        log.info("Round %d: generator proposed %d candidate solvents", round_idx, len(pool))
        return pool

    # ------------------------------------------------------------------
    # REINVENT 4
    # ------------------------------------------------------------------
    def _write_toml(self, workdir: Path, round_idx: int) -> Path:
        rc = self.cfg["reinvent"]
        prior = resolve(rc["prior_file"])
        if not prior.exists():
            raise FileNotFoundError(f"REINVENT prior not found: {prior} (see README: download priors)")
        agent = self.agent_file or prior
        scorer_args = f"-m alumina_pipeline.reinvent_scorer --config {self.scorer_config}"
        alerts = ", ".join(f'"{s}"' for s in TOXIC_SMARTS)
        device = "cuda:0" if self.device == "cuda" else "cpu"

        toml = f"""# Auto-generated by alumina_pipeline (round {round_idx})
run_type = "staged_learning"
device = "{device}"
tb_logdir = "tb_logs"
json_out_config = "_staged_learning.json"

[parameters]
summary_csv_prefix = "round{round_idx:02d}"
use_checkpoint = {"true" if self.agent_file else "false"}
purge_memories = false
prior_file = "{prior}"
agent_file = "{agent}"
batch_size = {rc["batch_size"]}
unique_sequences = true
randomize_smiles = true

[learning_strategy]
type = "dap"
sigma = {rc["sigma"]}
rate = {rc["learning_rate"]}

[diversity_filter]
type = "IdenticalMurckoScaffold"
bucket_size = 25
minscore = 0.3

[[stage]]
chkpt_file = "agent_round{round_idx:02d}.chkpt"
termination = "simple"
max_score = 1.0
min_steps = {rc["steps_per_round"]}
max_steps = {rc["steps_per_round"]}

[stage.scoring]
type = "geometric_mean"

[[stage.scoring.component]]
[stage.scoring.component.custom_alerts]
[[stage.scoring.component.custom_alerts.endpoint]]
name = "Toxicity alerts"
params.smarts = [{alerts}]

[[stage.scoring.component]]
[stage.scoring.component.ExternalProcess]
[[stage.scoring.component.ExternalProcess.endpoint]]
name = "IL/DES constraints x BoTorch acquisition"
weight = 1
params.executable = "{sys.executable}"
params.args = "{scorer_args}"
"""
        path = workdir / f"round{round_idx:02d}.toml"
        path.write_text(toml)
        return path

    def _run_reinvent(self, round_idx: int) -> list[str]:
        workdir = self.run_dir / "reinvent"
        workdir.mkdir(parents=True, exist_ok=True)
        toml = self._write_toml(workdir, round_idx)
        cmd = [self.cfg["reinvent"]["executable"], "-l", f"round{round_idx:02d}.log", str(toml.name)]
        log.info("Running REINVENT: %s", shlex.join(cmd))
        subprocess.run(cmd, cwd=workdir, check=True)

        self.agent_file = workdir / f"agent_round{round_idx:02d}.chkpt"
        csvs = sorted(workdir.glob(f"round{round_idx:02d}*.csv"))
        if not csvs:
            raise RuntimeError(f"REINVENT produced no summary CSV in {workdir}")
        df = pd.concat(pd.read_csv(c) for c in csvs)
        cols = {c.lower(): c for c in df.columns}
        smi_col, score_col = cols.get("smiles"), cols.get("score")
        if score_col:
            df = df[df[score_col] > 0].sort_values(score_col, ascending=False)
        return list(dict.fromkeys(df[smi_col].dropna().astype(str)))
